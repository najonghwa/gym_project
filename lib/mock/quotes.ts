export function seedFromDate(d = new Date()): number {
  const s = `${d.getFullYear()}-${d.getMonth()}-${d.getDate()}`;
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0;
  return Math.abs(h);
}

export function dailyQuote(d = new Date()): string {
  return QUOTES[seedFromDate(d) % QUOTES.length];
}
