def attach(D, NODES, REC=None):
    """공식마다 use(용도 · 식의 요지)를 붙인다."""
    U = build(D, NODES, REC)
    for n in NODES:
        for f in n["formulas"]: f["use"] = U[f["k"]]
    return NODES
